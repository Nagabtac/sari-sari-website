package myuniquesite.blerp.dto;

import java.math.BigDecimal;
import java.time.LocalDateTime;

public class UtangRequest {
    private String customerName;

    private String fname;

    private String lname;

    private Integer customerId; // Optional - if provided, use existing customer

    private BigDecimal amount; // Payment amount

    private BigDecimal balance; // Payment balance (defaults to amount if not provided)

    private String method; // Payment method (e.g., "credit")

    private String status; // Payment status (e.g., "FULL_BALANCE", "PARTIALY", "FULLY_PAID")

    @com.fasterxml.jackson.annotation.JsonAlias("pay_date")
    @com.fasterxml.jackson.annotation.JsonFormat(shape = com.fasterxml.jackson.annotation.JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime payDate; // Payment date

    // Getters and Setters

    public String getCustomerName() {
        return customerName;
    }

    public void setCustomerName(String customerName) {
        this.customerName = customerName;
    }

    public String getFname() {
        return fname;
    }

    public void setFname(String fname) {
        this.fname = fname;
    }

    public String getLname() {
        return lname;
    }

    public void setLname(String lname) {
        this.lname = lname;
    }

    public Integer getCustomerId() {
        return customerId;
    }

    public void setCustomerId(Integer customerId) {
        this.customerId = customerId;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public void setAmount(BigDecimal amount) {
        this.amount = amount;
    }

    public BigDecimal getBalance() {
        return balance;
    }

    public void setBalance(BigDecimal balance) {
        this.balance = balance;
    }

    public String getMethod() {
        return method;
    }

    public void setMethod(String method) {
        this.method = method;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public LocalDateTime getPayDate() {
        return payDate;
    }

    public void setPayDate(LocalDateTime payDate) {
        this.payDate = payDate;
    }
}
